#!/usr/bin/env python3
"""Generate the Unicode 17 extended-grapheme properties from pinned UCD files."""

import argparse
from concurrent.futures import ThreadPoolExecutor
from hashlib import sha256
from itertools import chain
import json
from pathlib import Path
import sys
from urllib.parse import urlsplit
from urllib.request import urlopen


ROOT = Path(__file__).resolve().parents[1]
VERSION = "17.0.0"
UCD = ROOT / "unicode" / VERSION
OUTPUT = ROOT / "src" / "unicode_grapheme.inc"
SCALAR_SPACE = 0x110000
GCB = {
    "CR": 1,
    "LF": 2,
    "Control": 3,
    "Extend": 4,
    "ZWJ": 5,
    "Regional_Indicator": 6,
    "Prepend": 7,
    "SpacingMark": 8,
    "L": 9,
    "V": 10,
    "T": 11,
    "LV": 12,
    "LVT": 13,
}
INCB = {"Consonant": 1, "Extend": 2, "Linker": 3}


def verify_upstream(entry):
    address = urlsplit(entry["url"])
    if address.scheme != "https" or address.netloc != "www.unicode.org":
        raise ValueError(f'{entry["name"]}: expected an official HTTPS Unicode URL')
    with urlopen(entry["url"], timeout=30) as response:
        if response.read() != (UCD / entry["name"]).read_bytes():
            raise ValueError(f'{entry["name"]}: upstream and vendored bytes differ')


def verify_sources(upstream):
    manifest = json.loads((UCD / "SOURCES.json").read_text(encoding="utf-8"))
    if manifest["version"] != VERSION:
        raise ValueError("Unexpected Unicode version")
    names = set()
    for entry in manifest["sources"]:
        name = entry["name"]
        if name in names or Path(name).name != name:
            raise ValueError(f"Invalid or duplicate Unicode source {name}")
        names.add(name)
        data = (UCD / name).read_bytes()
        if sha256(data).hexdigest() != entry["sha256"]:
            raise ValueError(f"{name}: SHA-256 mismatch")
        if "bytes" in entry and len(data) != entry["bytes"]:
            raise ValueError(f"{name}: byte count mismatch")
    if {p.name for p in UCD.glob("*.txt")} != names:
        raise ValueError("Unicode manifest does not cover the vendored text files")
    if upstream:
        with ThreadPoolExecutor(max_workers=6) as workers:
            list(workers.map(verify_upstream, manifest["sources"]))
    return len(names)


def records(name):
    with (UCD / name).open(encoding="utf-8") as stream:
        for line in stream:
            body = line.split("#", 1)[0].strip()
            if not body:
                continue
            codepoints, *properties = (item.strip() for item in body.split(";"))
            first, separator, last = codepoints.partition("..")
            start = int(first, 16)
            stop = int(last, 16) + 1 if separator else start + 1
            if not 0 <= start < stop <= SCALAR_SPACE:
                raise ValueError(f"{name}: invalid code point range {codepoints}")
            yield start, stop, properties


def assign(values, start, stop, value):
    if any(values[start:stop]):
        raise ValueError(f"Overlapping Unicode property range at U+{start:04X}")
    values[start:stop] = bytes([value]) * (stop - start)


def grapheme_flags():
    grapheme, indic, pictographic = (bytearray(SCALAR_SPACE) for _ in range(3))
    for start, stop, properties in records("GraphemeBreakProperty.txt"):
        assign(grapheme, start, stop, GCB[properties[0]])
    for start, stop, properties in records("DerivedCoreProperties.txt"):
        if properties[0] == "InCB":
            assign(indic, start, stop, INCB[properties[1]])
    for start, stop, properties in records("emoji-data.txt"):
        if properties[0] == "Extended_Pictographic":
            assign(pictographic, start, stop, 1)
    return (g | i << 4 | e << 6 for g, i, e in zip(grapheme, indic, pictographic))


def render():
    lines = [
        f"/* Generated by tools/generate_unicode_grapheme.py from Unicode {VERSION}.",
        " * Unicode License V3 accompanies the data in unicode/17.0.0/LICENSE.txt. */",
        f'static const char grapheme_unicode_version[] = "{VERSION}";',
        "static const GraphemeRange grapheme_ranges[] = {",
    ]
    first = 0
    previous = 0
    # A zero sentinel closes any final non-default run.
    for index, flags in enumerate(chain(grapheme_flags(), (0,))):
        if flags != previous:
            if previous:
                lines.append(f"    {{0x{first:06X}, 0x{index - 1:06X}, 0x{previous:02X}}},")
            first, previous = index, flags
    lines.append("};")
    return ("\n".join(lines) + "\n").encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the committed generated table")
    parser.add_argument("--verify-upstream", action="store_true",
                        help="also compare vendored files with official Unicode URLs")
    args = parser.parse_args()
    try:
        files = verify_sources(args.verify_upstream)
        contents = render()
        if args.check:
            if OUTPUT.read_bytes() != contents:
                raise ValueError("Grapheme table is out of date")
        else:
            OUTPUT.write_bytes(contents)
    except (OSError, ValueError, KeyError) as error:
        parser.exit(1, f"{error}\n")
    print(f"Verified Unicode {VERSION} inputs ({files} files) and generated table ({len(contents)} bytes).")
    if args.verify_upstream:
        print(f"All {files} official Unicode downloads match the vendored files byte for byte.")


if __name__ == "__main__":
    sys.exit(main())
