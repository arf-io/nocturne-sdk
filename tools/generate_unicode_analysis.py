#!/usr/bin/env python3
"""Generate the Unicode 17 line break, bidi, and script tables."""

import argparse
from itertools import chain
import re

from generate_unicode_grapheme import ROOT, SCALAR_SPACE, UCD, VERSION, records, verify_sources
from generate_unicode_width import unicode_categories


BIDI = dict(zip(
    "Left_To_Right Right_To_Left Arabic_Letter European_Number Arabic_Number "
    "European_Separator European_Terminator Common_Separator Nonspacing_Mark "
    "Boundary_Neutral Paragraph_Separator Segment_Separator White_Space Other_Neutral "
    "Left_To_Right_Embedding Left_To_Right_Override Right_To_Left_Embedding "
    "Right_To_Left_Override Pop_Directional_Format Left_To_Right_Isolate "
    "Right_To_Left_Isolate First_Strong_Isolate Pop_Directional_Isolate".split(),
    "L R AL EN AN ES ET CS NSM BN B S WS ON LRE LRO RLE RLO PDF LRI RLI FSI PDI".split(),
))


def unicode_table():
    return [
        f"/* Generated by tools/generate_unicode_analysis.py from Unicode {VERSION}.",
        " * Unicode License V3 accompanies the data in unicode/17.0.0/LICENSE.txt. */",
    ]


def compact(values):
    first = previous = 0
    for at, value in enumerate(chain(values, (0,))):
        if value != previous:
            if previous:
                yield first, at - 1, previous
            first, previous = at, value


def range_rows(rows, value):
    end = -1
    for first, last, entry in rows:
        if not end < first <= last < SCALAR_SPACE:
            raise ValueError(f"Unsorted or overlapping Unicode range at {first:X}")
        end = last
        yield f"    {{0x{first:06X}, 0x{last:06X}, {value(entry)}}},"


def line_data():
    rows = [(first, stop - 1, p[0]) for first, stop, p in records("LineBreak.txt")]
    classes = sorted({value for _, _, value in rows} - {"XX"})
    names = ["XX", *classes]
    cat_bits = {"Mn": 1, "Mc": 1, "Pi": 2, "Pf": 4, "Cn": 8}
    flags = bytearray([cat_bits["Cn"]]) * SCALAR_SPACE
    for first, stop, category in unicode_categories():
        flags[first:stop] = bytes([cat_bits.get(category, 0)]) * (stop - first)
    for name, selected, bit in [
        ("EastAsianWidth.txt", {"F", "W", "H"}, 16),
        ("emoji-data.txt", {"Extended_Pictographic"}, 32),
    ]:
        for first, stop, p in records(name):
            if p[0] in selected:
                for at in range(first, stop):
                    flags[at] |= bit
    return [
        *unicode_table(),
        "typedef enum LineClass {",
        *(f"    LB_{name}," for name in names),
        "} LineClass;",
        "static const AnalysisRange line_classes[] = {",
        *range_rows(rows, lambda value: f"LB_{value}"),
        "};",
        "static const AnalysisRange line_flags[] = {",
        *range_rows(compact(flags), lambda value: f"0x{value:02X}"),
        "};",
    ]


def bidi_data():
    names = list(BIDI.values())
    ids = {name: index for index, name in enumerate(names)}
    classes = bytearray(SCALAR_SPACE)
    data = (UCD / "DerivedBidiClass.txt").read_text(encoding="utf-8")
    for first, last, long_name in re.findall(r"@missing:\s*([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)", data):
        start, stop = int(first, 16), int(last or first, 16) + 1
        classes[start:stop] = bytes([ids[BIDI[long_name]]]) * (stop - start)
    for start, stop, p in records("DerivedBidiClass.txt"):
        classes[start:stop] = bytes([ids[p[0]]]) * (stop - start)

    lines = [
        *unicode_table(),
        "typedef enum BidiClass {",
        *(f"    BC_{name}," for name in names),
        "} BidiClass;",
        "static const AnalysisRange bidi_classes[] = {",
        *range_rows(compact(classes), lambda value: f"BC_{names[value]}"),
        "};",
    ]
    for file, table in [("BidiBrackets.txt", "bidi_brackets"), ("BidiMirroring.txt", "bidi_mirrors")]:
        lines.append(f"static const BidiPair {table}[] = {{")
        for first, stop, p in sorted(records(file)):
            if first + 1 != stop:
                raise ValueError(f"{file}: expected singleton")
            pair = int(p[0], 16)
            bracket = {"o": "BRACKET_OPEN", "c": "BRACKET_CLOSE"}[p[1]] if len(p) > 1 else "BRACKET_NONE"
            lines.append(f"    {{0x{first:06X}, 0x{pair:06X}, {bracket}}},")
        lines.append("};")
    return lines


def script_data():
    aliases = {}
    for line in (UCD / "PropertyValueAliases.txt").read_text(encoding="utf-8").splitlines():
        prop, *values = (item.strip() for item in line.split("#", 1)[0].split(";"))
        if prop == "sc":
            aliases.update((item, values[0]) for item in values)
    tags = sorted(set(aliases.values()))
    ids = {tag: index for index, tag in enumerate(tags)}
    # Four 64-bit words leave room for the complete Unicode 17 script set.
    if len(tags) > 256 or any(not re.fullmatch("[A-Za-z]{4}", tag) for tag in tags):
        raise ValueError("Unexpected Unicode script set")
    scripts = sorted((start, stop - 1, ids[aliases[p[0]]])
                     for start, stop, p in records("Scripts.txt"))
    extensions = []
    for start, stop, p in records("ScriptExtensions.txt"):
        mask = [0] * 4
        for value in p[0].split():
            index = ids[aliases[value]]
            mask[index // 64] |= 1 << (index % 64)
        extensions.append((start, stop - 1, mask))
    return [
        *unicode_table(),
        f"enum {{ SCRIPT_COUNT = {len(tags)}, SCRIPT_COMMON = {ids['Zyyy']},",
        f"       SCRIPT_INHERITED = {ids['Zinh']}, SCRIPT_UNKNOWN = {ids['Zzzz']} }};",
        "static const char script_tags[][5] = {",
        *(f'    "{tag}",' for tag in tags),
        "};",
        "static const AnalysisRange script_primary[] = {",
        *range_rows(scripts, str),
        "};",
        "static const ScriptRange script_extensions[] = {",
        *range_rows(sorted(extensions),
                    lambda mask: "{{" + ", ".join(f"UINT64_C(0x{word:016X})" for word in mask) + "}}"),
        "};",
    ]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the committed tables")
    args = parser.parse_args()
    try:
        files = verify_sources(False)
        for name, generator in [("linebreak", line_data), ("bidi", bidi_data), ("scripts", script_data)]:
            path = ROOT / "src" / f"unicode_{name}.inc"
            expected = ("\n".join(generator()) + "\n").encode("utf-8")
            if args.check:
                if path.read_bytes() != expected:
                    raise ValueError(f"{path.name} is out of date")
            else:
                path.write_bytes(expected)
    except (OSError, ValueError, KeyError) as error:
        parser.exit(1, f"{error}\n")
    print(f"Verified Unicode {VERSION} inputs ({files} files) and line-break, bidi, and script tables.")


if __name__ == "__main__":
    main()
