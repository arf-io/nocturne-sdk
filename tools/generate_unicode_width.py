#!/usr/bin/env python3
"""Generate terminal-width properties from Nocturne's pinned Unicode data."""

import argparse
from itertools import chain

from generate_unicode_grapheme import ROOT, SCALAR_SPACE, UCD, VERSION, records, verify_sources


OUTPUT = ROOT / "src" / "unicode_width.inc"
FLAGS = {
    "WIDE": 1 << 0,
    "AMBIGUOUS": 1 << 1,
    "MARK": 1 << 2,
    "IGNORABLE": 1 << 3,
    "CONTROL": 1 << 4,
    "EXTEND": 1 << 5,
    "EMOJI": 1 << 6,
    "PICTOGRAPH": 1 << 7,
    "MODIFIER": 1 << 8,
    "MODIFIER_BASE": 1 << 9,
    "TEXT_VARIATION": 1 << 10,
    "EMOJI_VARIATION": 1 << 11,
}


def unicode_categories():
    pending = None
    with (UCD / "UnicodeData.txt").open(encoding="utf-8") as stream:
        for line in stream:
            code, name, category, *_ = line.split(";")
            scalar = int(code, 16)
            if name.endswith(", First>"):
                if pending is not None:
                    raise ValueError("Unterminated UnicodeData range")
                pending = scalar, category
            elif name.endswith(", Last>"):
                if pending is None or pending[1] != category or pending[0] >= scalar:
                    raise ValueError("Invalid UnicodeData range")
                yield pending[0], scalar + 1, category
                pending = None
            else:
                if pending is not None:
                    raise ValueError("Unterminated UnicodeData range")
                yield scalar, scalar + 1, category
    if pending is not None:
        raise ValueError("Unterminated UnicodeData range")


def width_flags():
    values = [0] * SCALAR_SPACE

    def add(start, stop, flag):
        for index in range(start, stop):
            values[index] |= FLAGS[flag]

    for start, stop, props in records("EastAsianWidth.txt"):
        if props[0] in ("W", "F"):
            add(start, stop, "WIDE")
        elif props[0] == "A":
            add(start, stop, "AMBIGUOUS")
    for start, stop, category in unicode_categories():
        if category in ("Cc", "Cf", "Zl", "Zp"):
            add(start, stop, "CONTROL")
    for start, stop, props in records("DerivedCoreProperties.txt"):
        if props[0] == "Default_Ignorable_Code_Point":
            add(start, stop, "IGNORABLE")
    for start, stop, props in records("GraphemeBreakProperty.txt"):
        if props[0] == "Extend":
            add(start, stop, "EXTEND")
        elif props[0] == "SpacingMark":
            # GCB, not the general category, determines which spacing
            # marks can attach to a text base or a dotted-circle fallback.
            add(start, stop, "MARK")
        elif props[0] == "Prepend":
            # Unicode 17's format characters with this property are
            # visible prepended concatenation marks.
            for index in range(start, stop):
                values[index] &= ~FLAGS["CONTROL"]
    emoji_flags = {
        "Emoji_Presentation": "EMOJI",
        "Extended_Pictographic": "PICTOGRAPH",
        "Emoji_Modifier": "MODIFIER",
        "Emoji_Modifier_Base": "MODIFIER_BASE",
    }
    for start, stop, props in records("emoji-data.txt"):
        if props[0] in emoji_flags:
            add(start, stop, emoji_flags[props[0]])
    with (UCD / "emoji-variation-sequences.txt").open(encoding="utf-8") as stream:
        for line in stream:
            body = line.split("#", 1)[0].strip()
            if not body:
                continue
            sequence, style, _ = (item.strip() for item in body.split(";"))
            base, selector = (int(code, 16) for code in sequence.split())
            flag = {("text style", 0xFE0E): "TEXT_VARIATION",
                    ("emoji style", 0xFE0F): "EMOJI_VARIATION"}[(style, selector)]
            add(base, base + 1, flag)
    return values


def render():
    lines = [
        f"/* Generated by tools/generate_unicode_width.py from Unicode {VERSION}.",
        " * Unicode License V3 accompanies the data in unicode/17.0.0/LICENSE.txt. */",
        "enum {",
        *(f"    W_{name} = 0x{flag:04X}," for name, flag in FLAGS.items()),
        "};",
        "static const WidthRange width_ranges[] = {",
    ]
    first = previous = 0
    for index, flags in enumerate(chain(width_flags(), (0,))):
        if flags != previous:
            if previous:
                lines.append(f"    {{0x{first:06X}, 0x{index - 1:06X}, 0x{previous:04X}}},")
            first, previous = index, flags
    lines.append("};")
    return ("\n".join(lines) + "\n").encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the committed generated table")
    args = parser.parse_args()
    try:
        files = verify_sources(False)
        contents = render()
        if args.check:
            if OUTPUT.read_bytes() != contents:
                raise ValueError("Width table is out of date")
        else:
            OUTPUT.write_bytes(contents)
    except (OSError, ValueError, KeyError) as error:
        parser.exit(1, f"{error}\n")
    print(f"Verified Unicode {VERSION} inputs ({files} files) and width table ({len(contents)} bytes).")


if __name__ == "__main__":
    main()
